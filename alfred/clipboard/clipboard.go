// Package clipboard writes secrets to the macOS pasteboard, marked as
// concealed and transient so clipboard managers (including Alfred's
// clipboard history) don't record them, and clears them again later.
package clipboard

import (
	"bytes"
	"fmt"
	"log"
	"os/exec"
	"strconv"
	"strings"
	"time"

	"github.com/rwilgaard/go-alfredutils/v2/alfred"
)

// ClearJob is the job name CopySecret schedules the clear under.
const ClearJob = "clear-clipboard"

// The secret is read from stdin so it never appears in the process list.
const copyScript = `
ObjC.import('AppKit');
function run() {
  var data = $.NSFileHandle.fileHandleWithStandardInput.readDataToEndOfFile;
  var str = $.NSString.alloc.initWithDataEncoding(data, $.NSUTF8StringEncoding);
  var pb = $.NSPasteboard.generalPasteboard;
  pb.clearContents;
  pb.setStringForType(str, $.NSPasteboardTypeString);
  pb.setStringForType($(''), 'org.nspasteboard.ConcealedType');
  pb.setStringForType($(''), 'org.nspasteboard.TransientType');
  pb.setStringForType($(''), 'org.nspasteboard.AutoGeneratedType');
  return String(pb.changeCount);
}
`

const clearScript = `
ObjC.import('AppKit');
function run(argv) {
  var pb = $.NSPasteboard.generalPasteboard;
  if (String(pb.changeCount) === argv[0]) {
    pb.clearContents;
    return 'cleared';
  }
  return 'changed';
}
`

// clearShell waits, then clears the pasteboard if it is unchanged. It runs as
// a background job, so the workflow needs no command of its own for it.
const clearShell = `sleep "$1" && exec /usr/bin/osascript -l JavaScript -e "$2" "$3"`

// execCommand is replaced in tests.
var execCommand = exec.Command

// Copy places value on the clipboard and returns the pasteboard change count
// after the write, which ClearIfUnchanged uses to detect later copies.
func Copy(value string) (int, error) {
	cmd := execCommand("/usr/bin/osascript", "-l", "JavaScript", "-e", copyScript)
	cmd.Stdin = strings.NewReader(value)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return 0, fmt.Errorf("copy to clipboard: %s: %w", strings.TrimSpace(stderr.String()), err)
	}
	n, err := strconv.Atoi(strings.TrimSpace(string(out)))
	if err != nil {
		return 0, fmt.Errorf("parse pasteboard change count %q: %w", out, err)
	}
	return n, nil
}

// ClearIfUnchanged clears the clipboard if nothing has been copied since the
// pasteboard had changeCount, and reports whether it cleared it.
func ClearIfUnchanged(changeCount int) (bool, error) {
	out, err := execCommand("/usr/bin/osascript", "-l", "JavaScript", "-e", clearScript, strconv.Itoa(changeCount)).Output()
	if err != nil {
		return false, fmt.Errorf("clear clipboard: %w", err)
	}
	return strings.TrimSpace(string(out)) == "cleared", nil
}

// CopySecret copies value and, when clearAfter is positive, clears it after
// that long unless something else was copied in the meantime. A newer
// CopySecret replaces a pending clear.
func CopySecret(wf *alfred.Workflow, value string, clearAfter time.Duration) error {
	n, err := Copy(value)
	if err != nil {
		return err
	}
	if clearAfter <= 0 {
		return nil
	}
	if err := wf.Kill(ClearJob); err != nil {
		log.Printf("kill previous clipboard clear: %v", err)
	}
	secs := strconv.FormatFloat(clearAfter.Seconds(), 'f', -1, 64)
	cmd := execCommand("/bin/sh", "-c", clearShell, "sh", secs, clearScript, strconv.Itoa(n))
	if err := wf.RunInBackground(ClearJob, cmd); err != nil {
		return fmt.Errorf("schedule clipboard clear: %w", err)
	}
	return nil
}
